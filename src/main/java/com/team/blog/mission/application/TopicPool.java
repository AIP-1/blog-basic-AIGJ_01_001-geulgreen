    /** 그날의 내장 주제 {@code count}개(최대 분야 수). 분야는 서로 다르고, 같은 분야 안에서는 날마다 다음 주제로. */
    public static List<Topic> forDay(LocalDate day, int count) {
        long d = day.toEpochDay();
        int n = CATEGORIES.size();
        int[] offsets = {0, 3, 5, 2, 6};
        List<Topic> out = new ArrayList<>();
        for (int k = 0; k < Math.min(count, offsets.length); k++) {
            List<Topic> category = CATEGORIES.get((int) Math.floorMod(d + offsets[k], n));
            out.add(category.get((int) Math.floorMod(d / n + k * 7L, category.size())));
        }
        return out;
    }

    public static int size() {
        return CATEGORIES.stream().mapToInt(List::size).sum();
    }
